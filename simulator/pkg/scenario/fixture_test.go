var update = flag.Bool("update", false, "rewrite testdata/variant and the golden files")

// fixtureDir is a variant directory of a scenario without variants, as
// plan, run and the simulator leave it. simscenario's tests evaluate it
// too, so it is a committed directory, regenerated by
// TestFixtureVariantDirUpToDate -update.
const fixtureDir = "testdata/variant"

// fxStart is the run's start; every record time is an offset from it.
var fxStart = time.Date(2026, 10, 4, 20, 0, 0, 0, time.UTC)

func fxAt(sec float64) time.Time { return fxStart.Add(time.Duration(sec * float64(time.Second))) }

