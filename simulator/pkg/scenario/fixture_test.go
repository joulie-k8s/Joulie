// fxEnv is the fixture's variant.env: the dev timing's 10 s reconcile, the
// default 30 s cache TTL (a 40 s placement grace) and a 1 m rate window (a
// 2 m twinPower warmup).
func fxEnv() scenario.VariantEnv {
	return scenario.VariantEnv{
		Scenario: "fixture", RunID: "20261004T200000Z-fixture-0123456789ab", ClusterName: "smoke",
		Spec: "tests/simcluster/specs/smoke.yaml", Timing: "dev", Telemetry: "otel", PowerScope: "components", Isolation: scenario.IsolationReuse,
		JoulieEnabled: true, ControllerReconcile: 10 * time.Second, CacheTTL: 30 * time.Second, RateWindow: time.Minute,
		GitSHA: "0123456789abcdef0123456789abcdef01234567",
	}
}

func fxDecode(t testing.TB, doc string) scenario.Scenario {
	t.Helper()
	var s scenario.Scenario
	if err := yaml.UnmarshalStrict([]byte(doc), &s); err != nil {
		t.Fatalf("decode: %v", err)
	}
	return s
}

func fxResource(service string) otlpjson.Resource {
	return otlpjson.Resource{Attributes: []otlpjson.KeyValue{
		otlpjson.String(semconv.AttrServiceName, service),
		otlpjson.String(semconv.AttrSimRunID, fxEnv().RunID),
	}}
}

// fxEvent is one simulator event at offset sec.
func fxEvent(e semconv.Event, sec float64, attrs ...otlpjson.KeyValue) otlpjson.LogRecord {
	return otlpjson.LogRecord{TimeUnixNano: otlpjson.Uint64String(fxAt(sec).UnixNano()), ObservedTimeUnixNano: otlpjson.Uint64String(fxAt(sec).UnixNano()),
		SeverityNumber: e.SeverityNumber, SeverityText: e.SeverityText, EventName: e.Name, Attributes: attrs}
}

func fxJob(id, class string, extra ...otlpjson.KeyValue) []otlpjson.KeyValue {
	return append([]otlpjson.KeyValue{otlpjson.String(semconv.AttrSimJobID, id), otlpjson.String(semconv.AttrJoulieWorkloadClass, class)}, extra...)
}

func fxScheduled(id, class, node, nodeClass string, sec, since, wait float64) otlpjson.LogRecord {
	return fxEvent(semconv.EventSimJobScheduled, sec, fxJob(id, class,
		otlpjson.String(semconv.AttrK8sNodeName, node), otlpjson.String(semconv.AttrJoulieNodePowerProfile, nodeClass),
		otlpjson.String(semconv.AttrJoulieNodeSchedulableClass, nodeClass), otlpjson.Double(semconv.AttrJoulieNodeClassSince, since),
		otlpjson.Double(semconv.AttrSimJobQueueWait, wait))...)
}

func fxCompleted(id, class string, sec, duration, run float64) otlpjson.LogRecord {
	return fxEvent(semconv.EventSimJobCompleted, sec, fxJob(id, class,
		otlpjson.Double(semconv.AttrSimJobDuration, duration), otlpjson.Double(semconv.AttrSimJobRunTime, run),
		otlpjson.Double(semconv.AttrSimJobIdealRunTime, 60))...)
}

// fxEnergySeries are the energy series of the fixture: node, class, hw.type
// and constant power, so the energy at a snapshot is power x offset.
var fxEnergySeries = []struct {
	node, class, hw string
	watts           float64
}{
	{"intel-0", "performance", "cpu", 150}, {"intel-0", "idle", "cpu", 50},
	{"nvl-0", "standard", "cpu", 100}, {"nvl-0", "standard", "gpu", 400}, {"nvl-0", "idle", "gpu", 100},
}

func fxEnergy(sec float64) otlpjson.Metric {
	sum := &otlpjson.Sum{AggregationTemporality: otlpjson.AggregationTemporalityCumulative, IsMonotonic: true}
	for _, s := range fxEnergySeries {
		v := s.watts * sec
		sum.DataPoints = append(sum.DataPoints, otlpjson.NumberDataPoint{
			Attributes: []otlpjson.KeyValue{otlpjson.String(semconv.AttrJoulieWorkloadClass, s.class), otlpjson.String(semconv.AttrHwType, s.hw),
				otlpjson.String(semconv.AttrK8sNodeName, s.node), otlpjson.String(semconv.AttrSimProfile, "p")},
			StartTimeUnixNano: otlpjson.Uint64String(fxStart.UnixNano()), TimeUnixNano: otlpjson.Uint64String(fxAt(sec).UnixNano()), AsDouble: &v,
		})
	}
	return otlpjson.Metric{Name: semconv.JoulieSimWorkloadEnergy.Name, Unit: "J", Sum: sum}
}

func fxWork(sec float64) otlpjson.Metric {
	sum := &otlpjson.Sum{AggregationTemporality: otlpjson.AggregationTemporalityCumulative, IsMonotonic: true}
	for _, w := range []struct {
		class string
		units float64
	}{{"performance", 480}, {"standard", 240}} {
		v := w.units
		sum.DataPoints = append(sum.DataPoints, otlpjson.NumberDataPoint{
			Attributes:        []otlpjson.KeyValue{otlpjson.String(semconv.AttrJoulieWorkloadClass, w.class), otlpjson.String(semconv.AttrSimWorkKind, semconv.WorkKindCPU)},
			StartTimeUnixNano: otlpjson.Uint64String(fxStart.UnixNano()), TimeUnixNano: otlpjson.Uint64String(fxAt(sec).UnixNano()), AsDouble: &v,
		})
	}
	return otlpjson.Metric{Name: semconv.JoulieSimWorkloadWork.Name, Unit: "{unit}", Sum: sum}
}

// fxTwins are the NodeTwin samples: intel-0 reads 5 % above its 200 W,
// nvl-0 its 600 W exactly.
func fxTwins(sec float64) otlpjson.Metric {
	g := &otlpjson.Gauge{}
	for _, s := range []struct {
		node  string
		watts float64
	}{{"intel-0", 210}, {"nvl-0", 600}} {
		v := s.watts
		g.DataPoints = append(g.DataPoints, otlpjson.NumberDataPoint{
			Attributes:   []otlpjson.KeyValue{otlpjson.String(semconv.AttrK8sNodeName, s.node), otlpjson.String(semconv.AttrJoulieNodeTwinPowerSource, "prometheus")},
			TimeUnixNano: otlpjson.Uint64String(fxAt(sec).UnixNano()), AsDouble: &v,
		})
	}
	return otlpjson.Metric{Name: semconv.JoulieCaptureNodeTwinMeasuredPower.Name, Unit: "W", Gauge: g}
}

func fxJSONL(t testing.TB, path string, lines ...any) {
	t.Helper()
	var b bytes.Buffer
	for _, l := range lines {
		j, err := json.Marshal(l)
		if err != nil {
			t.Fatal(err)
		}
		b.Write(append(j, '\n'))
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, b.Bytes(), 0o644); err != nil {
		t.Fatal(err)
	}
}

func fxLogs(service string, recs ...otlpjson.LogRecord) otlpjson.LogsData {
	return otlpjson.LogsData{ResourceLogs: []otlpjson.ResourceLogs{{Resource: fxResource(service), SchemaURL: semconv.SchemaURL,
		ScopeLogs: []otlpjson.ScopeLogs{{Scope: otlpjson.Scope{Name: workload.ScopeName}, LogRecords: recs}}}}}
}

func fxMetrics(service string, ms ...otlpjson.Metric) otlpjson.MetricsData {
	return otlpjson.MetricsData{ResourceMetrics: []otlpjson.ResourceMetrics{{Resource: fxResource(service), SchemaURL: semconv.SchemaURL,
		ScopeMetrics: []otlpjson.ScopeMetrics{{Scope: otlpjson.Scope{Name: workload.ScopeName}, Metrics: ms}}}}}
}

// writeFixture writes the fixture variant directory into dir.
func writeFixture(t testing.TB, dir string) {
	t.Helper()
	s := scenario.Effective(fxDecode(t, fxScenario))
	b, err := yaml.Marshal(s)
	if err != nil {
		t.Fatal(err)
	}
	trace, err := scenario.RenderJobs(s)
	if err != nil {
		t.Fatal(err)
	}
	status := workload.RunStatus{RunID: fxEnv().RunID, Phase: workload.PhaseAborted, StartedAt: fxStart, ElapsedSeconds: 200, AllSubmitted: false,
		Jobs: workload.RunJobCounts{Total: 6, NotDue: 1, Completed: 3, Failed: 1, Incomplete: 1}}
	st, err := json.MarshalIndent(status, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	for name, data := range map[string][]byte{
		scenario.ScenarioEffectiveFile: b, workload.TraceFile: trace, scenario.VariantEnvFile: fxEnv().Marshal(),
		scenario.RunStatusFile: append(st, '\n'),
	} {
		if err := os.WriteFile(filepath.Join(dir, name), data, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	sim := "joulie-simulator"
	stalled := otlpjson.String(semconv.AttrSimStallReason, semconv.StallReasonNoProgress)
	fxJSONL(t, filepath.Join(dir, workload.OTLPDir, workload.SimulatorLogsFile),
		fxLogs(sim, fxEvent(semconv.EventSimRunStarted, 0, otlpjson.Int(semconv.AttrSimRunJobs, 6)),
			fxEvent(semconv.EventSimJobSubmitted, 0, fxJob("perf-0-0", "performance")...),
			fxEvent(semconv.EventSimJobSubmitted, 0, fxJob("std-0-0", "standard")...),
			fxEvent(semconv.EventSimJobSubmitted, 0, fxJob("late-0-0", "standard")...),
			fxScheduled("perf-0-0", "performance", "intel-0", "performance", 2, 100, 2),
			fxScheduled("std-0-0", "standard", "nvl-0", "eco", 3, 200, 3),
			fxScheduled("late-0-0", "standard", "intel-0", "performance", 4, 100, 4)),
		fxLogs(sim, fxEvent(semconv.EventSimJobSubmitted, 30, fxJob("perf-1-0", "performance")...),
			// A bind 5 s after intel-0 turned eco: inside the 40 s grace.
			fxScheduled("perf-1-0", "performance", "intel-0", "eco", 31, 5, 1),
			fxEvent(semconv.EventSimJobSubmitted, 60, fxJob("std-1-0", "standard")...),
			fxScheduled("std-1-0", "standard", "nvl-0", "eco", 61, 260, 1),
			fxCompleted("std-0-0", "standard", 65, 65, 63),
			fxCompleted("perf-0-0", "performance", 70, 70, 66)),
		fxLogs(sim, fxEvent(semconv.EventSimJobFailed, 90, fxJob("std-1-0", "standard", otlpjson.String(semconv.AttrErrorType, semconv.ErrorTypePodFailed))...),
			fxCompleted("perf-1-0", "performance", 110, 80, 72),
			fxEvent(semconv.EventSimJobStalled, 120, fxJob("late-0-0", "standard", stalled, otlpjson.Double(semconv.AttrSimStallAge, 60))...),
			fxEvent(semconv.EventSimRunStalled, 150, otlpjson.String(semconv.AttrSimStallReason, semconv.StallReasonAllBlocked), otlpjson.Double(semconv.AttrSimStallAge, 60)),
			fxEvent(semconv.EventSimJobIncomplete, 200, fxJob("late-0-0", "standard")...),
			fxEvent(semconv.EventSimRunFinished, 200, otlpjson.Int(semconv.AttrSimRunJobs, 6))),
	)
	fxJSONL(t, filepath.Join(dir, workload.OTLPDir, workload.SimulatorMetricsFile),
		fxMetrics(sim, fxEnergy(60)), fxMetrics(sim, fxEnergy(120)), fxMetrics(sim, fxEnergy(180), fxWork(180)))
	targets := 3.0
	harness := scenario.ServiceName
	fxJSONL(t, filepath.Join(dir, workload.OTLPDir, scenario.HarnessMetricsFile),
		fxMetrics(harness, fxTwins(60)), fxMetrics(harness, fxTwins(120)), fxMetrics(harness, fxTwins(180)),
		fxMetrics(harness, otlpjson.Metric{Name: semconv.JoulieScenarioAssertionValue.Name, Unit: "{value}", Gauge: &otlpjson.Gauge{DataPoints: []otlpjson.NumberDataPoint{{
			Attributes: []otlpjson.KeyValue{otlpjson.String(semconv.AttrJoulieAssertionName, "targets"),
				otlpjson.String(semconv.AttrJoulieAssertionSource, semconv.AssertionSourceObserved)},
			TimeUnixNano: otlpjson.Uint64String(fxAt(200).UnixNano()), AsDouble: &targets}}}}))
	fxJSONL(t, filepath.Join(dir, workload.OTLPDir, scenario.HarnessLogsFile),
		fxLogs(harness, fxEvent(semconv.EventScenarioStarted, 0, otlpjson.String(semconv.AttrJoulieScenarioName, "fixture"),
			otlpjson.String(semconv.AttrJoulieScenarioVariant, ""))))
	for _, phase := range []string{scenario.SnapshotStart, scenario.SnapshotEnd} {
		if err := scenario.WriteKubeSnapshot(dir, phase, fxSnapshot(phase)); err != nil {
			t.Fatal(err)
		}
	}
}

// fxSnapshot is the cluster at a phase: two fake Nodes, their twins and
// hardware and, at the end, one complete Job, one failed Job and the late
// job's pod still running.
func fxSnapshot(phase string) scenario.KubeSnapshot {
	s := scenario.KubeSnapshot{Time: fxAt(0)}
	for _, n := range []string{"intel-0", "nvl-0"} {
		s.Nodes = append(s.Nodes, corev1.Node{ObjectMeta: metav1.ObjectMeta{Name: n,
			Annotations: map[string]string{clusterspec.KWOKAnnotation: clusterspec.KWOKValue}}})
		s.NodeHardwares = append(s.NodeHardwares, v1alpha1.NodeHardware{ObjectMeta: metav1.ObjectMeta{Name: n}})
	}
	s.NodeTwins = []v1alpha1.NodeTwin{
		{ObjectMeta: metav1.ObjectMeta{Name: "intel-0"}, Spec: v1alpha1.NodeTwinSpec{NodeName: "intel-0"},
			Status: v1alpha1.NodeTwinStatus{ControlStatus: &v1alpha1.ControlStatus{CPU: &v1alpha1.ControlResult{Backend: "rapl", Result: "applied"}}}},
		{ObjectMeta: metav1.ObjectMeta{Name: "nvl-0"}, Spec: v1alpha1.NodeTwinSpec{NodeName: "nvl-0"},
			Status: v1alpha1.NodeTwinStatus{ControlStatus: &v1alpha1.ControlStatus{GPU: &v1alpha1.ControlResult{Backend: "none", Result: "blocked"}}}},
	}
	if phase == scenario.SnapshotStart {
		return s
	}
	s.Time = fxAt(200)
	labels := map[string]string{workload.LabelPartOf: workload.PartOfWorkload, workload.LabelRunID: workload.RunLabelValue(fxEnv().RunID)}
	s.Jobs = []batchv1.Job{
		{ObjectMeta: metav1.ObjectMeta{Name: "sim-perf-0", Namespace: "default", Labels: labels},
			Status: batchv1.JobStatus{Conditions: []batchv1.JobCondition{{Type: batchv1.JobComplete, Status: corev1.ConditionTrue}}}},
		{ObjectMeta: metav1.ObjectMeta{Name: "sim-std-1", Namespace: "default", Labels: labels},
			Status: batchv1.JobStatus{Conditions: []batchv1.JobCondition{{Type: batchv1.JobFailed, Status: corev1.ConditionTrue}}}},
	}
	s.Pods = []corev1.Pod{
		{ObjectMeta: metav1.ObjectMeta{Name: "sim-perf-0-x", Namespace: "default", Labels: labels},
			Spec: corev1.PodSpec{NodeName: "intel-0"}, Status: corev1.PodStatus{Phase: corev1.PodSucceeded}},
		{ObjectMeta: metav1.ObjectMeta{Name: "sim-late-0-x", Namespace: "default", Labels: labels},
			Spec: corev1.PodSpec{NodeName: "intel-0"}, Status: corev1.PodStatus{Phase: corev1.PodRunning}},
	}
	return s
}

func readTree(t *testing.T, dir string) map[string][]byte {
	t.Helper()
	out := map[string][]byte{}
	err := filepath.WalkDir(dir, func(path string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		rel, _ := filepath.Rel(dir, path)
		b, err := os.ReadFile(path)
		out[rel] = b
		return err
	})
	if err != nil {
		t.Fatal(err)
	}
	return out
}

// The committed fixture is what writeFixture writes, so the fixture and its
// recipe cannot drift apart.
func TestFixtureVariantDirUpToDate(t *testing.T) {
	if *update {
		if err := os.RemoveAll(fixtureDir); err != nil {
			t.Fatal(err)
		}
		if err := os.MkdirAll(fixtureDir, 0o755); err != nil {
			t.Fatal(err)
		}
		writeFixture(t, fixtureDir)
	}
	tmp := t.TempDir()
	writeFixture(t, tmp)
	want, got := readTree(t, tmp), readTree(t, fixtureDir)
	var names []string
	for n := range want {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		if !bytes.Equal(want[n], got[n]) {
			t.Errorf("%s/%s differs from what writeFixture writes; run go test ./simulator/pkg/scenario/ -run TestFixtureVariantDirUpToDate -update", fixtureDir, n)
		}
	}
	if len(got) != len(want) {
		t.Errorf("%s has %d files, writeFixture writes %d", fixtureDir, len(got), len(want))
	}
}
